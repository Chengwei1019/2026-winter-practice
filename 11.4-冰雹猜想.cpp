/*冰雹猜想（也叫角谷猜想）：从任意正整数 n 出发，若 n 是偶数就把它除以 2，若 n 是奇数就把它变成 3n+1。反复这样做，最终会得到 1。
给定 n，输出从 n 变到 1 的整个序列（包含起点和终点）。
本题只使用变量、分支和循环，不需要数组、函数或字符串。
输入描述
一行一个整数 n（1 ≤ n ≤ 10000）。
输出描述
在一行中输出序列中的每个数，相邻两个数之间用一个空格分隔。序列以 n 开始、以 1 结束*/
#include<iostream>
using namespace std;
int main(){
    int n;
    cin>>n;
    if(n != 1){
        while(n != 1){
        cout<<n<<" ";
        if(n%2 == 1){
            n = n*3 + 1;
        }else if(n%2 == 0){
            n = n/2;
        }
        
    }
    }else if(n == 1){
        cout<<n<<endl;
    }
    return 0;
}